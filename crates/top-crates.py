#!/usr/bin/env python3
"""Write Cargo.toml's dependencies: the crates of play.rust-lang.org.

The Rust Playground offers the top 100 crates of crates.io, the crates of the
Rust Cookbook, and all their dependencies, each as a direct dependency (a
second version of a crate under a name like rand_0_8_8), at pinned versions
with the features it chose. Its top-crates tool generates that list as
compiler/base/Cargo.toml; this takes it, at the commit of the Rust Playground
the interface comes from (frontend/package.json), and leaves out the crates
that cannot work here (EXCLUDED).

Usage: crates/top-crates.py [upstream Cargo.toml]   (default: fetched from GitHub)
"""

import json
import pathlib
import subprocess
import sys
import tomllib
import urllib.request

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
CARGO = ["cargo", "+nightly-2026-10-19"]
TARGET = "wasm32-wasip1-threads"

# Crates programs cannot use in the browser, and why. Crates that depend on
# them are left out too.
EXCLUDED = {
    # The network: no sockets, so no HTTP, TLS or database clients.
    "reqwest": "network", "hyper": "network", "hyper-util": "network", "hyper-tls": "network",
    "hyper-rustls": "network", "h2": "network", "tower-http": "network",
    "postgres": "network", "tokio-postgres": "network",
    # C libraries that are not there: OpenSSL, and AWS-LC (built with CMake).
    "openssl-sys": "needs OpenSSL", "aws-lc-sys": "needs CMake and AWS-LC",
    # Other operating systems.
    "windows-sys": "Windows", "windows-targets": "Windows", "windows-link": "Windows",
    "windows_aarch64_gnullvm": "Windows", "windows_aarch64_msvc": "Windows",
    "windows_i686_gnu": "Windows", "windows_i686_msvc": "Windows", "windows_x86_64_gnu": "Windows",
    "windows_x86_64_gnullvm": "Windows", "windows_x86_64_msvc": "Windows",
    "linux-raw-sys": "Linux",
    # What WASI does not have, or this target.
    "socket2": "network", "signal-hook-registry": "no signals in WASI",
    "xattr": "no extended attributes in WASI", "cpufeatures": "x86 and Arm only",
    # A proc macro that reads Cargo.toml, which rustc's wasm interpreter gives
    # it no way to: it cannot build cookie_store's docs, or anything here.
    "document-features": "proc macro reads Cargo.toml", "cookie_store": "uses document-features",
}

# Features to add, by crate: parking_lot's thread parker needs "nightly" on
# wasm with threads (and the compiler is a nightly).
ADDED_FEATURES = {"parking_lot": ["nightly"], "parking_lot_core": ["nightly"]}

HEADER = """\
# The crates available to programs in the browser: play.rust-lang.org's (the
# top 100 crates of crates.io, the Rust Cookbook's, and their dependencies),
# but for those that cannot work here. Generated by top-crates.py from the
# Rust Playground's list; edit that instead. They are built for
# wasm32-wasip1-threads by the native rustc from the same source as
# rustc.wasm, so that rustc.wasm can read their metadata (build.py).
[package]
name = "playground-crates"
version = "0.0.0"
edition = "2024"
publish = false

[lib]
path = "lib.rs"

[dependencies]
"""


def upstream_manifest(path):
    if path:
        return pathlib.Path(path).read_text()
    upstream = json.loads((ROOT / "frontend/package.json").read_text())["upstream"]
    url = (upstream["repository"].replace("github.com", "raw.githubusercontent.com")
           + f"/{upstream['commit']}/compiler/base/Cargo.toml")
    with urllib.request.urlopen(url) as res:
        return res.read().decode()


def toml_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    return json.dumps(v)


def write(deps, keys):
    lines = []
    for key in sorted(keys):
        spec = dict(deps[key])
        name = spec["package"]
        if name in ADDED_FEATURES:
            spec["features"] = sorted(set(spec.get("features", [])) | set(ADDED_FEATURES[name]))
        fields = ", ".join(f"{k} = {toml_value(v)}" for k, v in spec.items())
        lines.append(f"{key} = {{ {fields} }}\n")
    (HERE / "Cargo.toml").write_text(HEADER + "".join(lines))


def reaching_excluded():
    """The dependencies (by key) that depend, at any depth, on an excluded crate."""
    meta = json.loads(subprocess.run(
        [*CARGO, "metadata", "--format-version=1", f"--filter-platform={TARGET}"],
        cwd=HERE, check=True, stdout=subprocess.PIPE, text=True).stdout)
    names = {p["id"]: p["name"] for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    bad = {}

    def reaches(pid):
        if pid not in bad:
            bad[pid] = False  # while it is being visited: a cycle adds nothing
            bad[pid] = names[pid] in EXCLUDED or any(reaches(d["pkg"]) for d in nodes[pid]["deps"])
        return bad[pid]

    # The root's dependencies are named by their keys.
    return {d["name"] for d in nodes[meta["resolve"]["root"]]["deps"] if reaches(d["pkg"])}


def main():
    deps = tomllib.loads(upstream_manifest(sys.argv[1] if len(sys.argv) > 1 else None))["dependencies"]
    keys = {k for k, spec in deps.items() if spec["package"] not in EXCLUDED}
    left_out = [f"{k} ({EXCLUDED[deps[k]['package']]})" for k in sorted(deps) if k not in keys]
    # Leave out what depends on what was left out, until nothing does.
    while True:
        write(deps, keys)
        dependents = keys & reaching_excluded()
        if not dependents:
            break
        keys -= dependents
        left_out += [f"{k} (uses one of those)" for k in sorted(dependents)]
    print(f"{len(keys)} crates; left out {len(left_out)}: {', '.join(left_out)}")


if __name__ == "__main__":
    main()
